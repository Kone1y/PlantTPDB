# 3. layout and drawing
# ===================================================================
def node_key(n):
    return n.name if n.is_leaf() else n.cid  # tips by name, internal nodes by CAFE id

def layout(root, use_blen=True):
    leaves = root.leaves()
    for i, lf in enumerate(leaves): lf.y = float(i)
    def setx(n, x0):
        n.x = x0 + (n.blen if use_blen else 1.0)
        for c in n.children: setx(c, n.x)
    root.x = 0.0
    for c in root.children: setx(c, 0.0)
    def sety(n):
        if n.is_leaf(): return n.y
        ys = [sety(c) for c in n.children]
        n.y = (min(ys) + max(ys)) / 2.0; return n.y
    sety(root)
    if not use_blen:  # cladogram: all tips aligned to the maximum depth
        depth = max(len(list(_anc(l))) for l in leaves)
        for l in leaves: l.x = float(depth)
    return leaves

def _anc(n):
    while n.parent is not None:
        yield n; n = n.parent

def prettify(name):
    return (name or "").replace("_", " ")

def _fmt_p(x):
    """Compact on-figure format for p / FDR: 0 -> "0", <1e-4 in scientific notation, else 3 significant digits."""
    if x is None:
        return "NA"
    if x == 0:
        return "0"
    if x < 1e-4:
        return f"{x:.2e}"
    return f"{x:.3g}"

def draw_tree(ax, root, branch_val, norm, *, lw=2.0, neutral="#d7d7d7",
              counts=None, sig=None, cmap=DIVER):
    segs, cols = [], []
    for n in root.walk():
        if n.parent is None: continue
        v = branch_val.get(node_key(n))
        cols.append(cmap(norm(v)) if v is not None else neutral)
        segs.append([(n.parent.x, n.y), (n.x, n.y)])
    vseg = [[(n.x, min(c.y for c in n.children)), (n.x, max(c.y for c in n.children))]
            for n in root.walk() if n.children]
    ax.add_collection(LineCollection(vseg, colors="#5a5a5a", linewidths=lw * 0.85,
                                     zorder=2, capstyle="round"))
    ax.add_collection(LineCollection(segs, colors=cols, linewidths=lw, zorder=3,
                                     capstyle="round"))
    if sig:
        pts = [(n.x, n.y) for n in root.walk() if sig.get(node_key(n))]
        if pts:
            ax.scatter(*zip(*pts), s=15, marker="*", color="#111", zorder=5, linewidths=0)
    if counts:
        for n in root.walk():
            k = node_key(n)
            if k in counts:
                # significant nodes (same set as the black stars) are colored by change direction:
                # red = expansion (change>0), blue = contraction (change<0), taken from the DIVER ends,
                # matching the branch color; non-significant nodes stay near-black.
                color = "#1a1a1a"
                if sig and sig.get(k):
                    v = branch_val.get(k)
                    if v is not None and v > 0:
                        color = "#B2182B"
                    elif v is not None and v < 0:
                        color = "#2166AC"
                ax.text(n.x, n.y, str(counts[k]), fontsize=6.2, ha="center", va="center",
                        color=color, zorder=6, bbox=dict(boxstyle="round,pad=0.18", fc="white",
                                                        ec="#9a9a9a", lw=0.5))
    return max(n.x for n in root.walk())

