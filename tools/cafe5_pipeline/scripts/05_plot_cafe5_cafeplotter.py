def _tip_stats(df):
    sp = [t for t in df.TaxonID.astype(str).unique() if any(c.isalpha() for c in t)]
    g = df[df.TaxonID.astype(str).isin(sp)].groupby(df.TaxonID.astype(str))
    net = {s: int(x.Change.sum()) for s, x in g}
    gained = {s: int(x.loc[x.Change > 0, "Change"].sum()) for s, x in g}
    lost = {s: int(-x.loc[x.Change < 0, "Change"].sum()) for s, x in g}
    return net, gained, lost

def figure_summary(root, df, out_base, formats, groups, vmax=None, use_blen=True,
                   title="Transporter gene-family expansion / contraction",
                   subtitle=None, fdr_map=None):
    net, gained, lost = _tip_stats(df)
    branch_val = {node_key(n): int(g.Change.sum())
                  for tid, g in df.groupby(df.TaxonID.astype(str))
                  for n in root.walk() if node_key(n) == tid}
    leaves = layout(root, use_blen); n = len(leaves)
    if vmax is None:
        vmax = max(1.0, float(np.percentile([abs(v) for v in branch_val.values()], 80)))
    norm = TwoSlopeNorm(vmin=-vmax, vcenter=0, vmax=vmax)

    fig = plt.figure(figsize=(7.2, max(4.5, 0.27 * n + 1.2)))
    gs = fig.add_gridspec(1, 3, width_ratios=[3.0, 1.85, 1.35], wspace=0.02,
                          left=0.055, right=0.965, top=0.885, bottom=0.09)
    axT = fig.add_subplot(gs[0, 0]); axB = fig.add_subplot(gs[0, 2], sharey=axT)
    axT.set_ylim(-0.9, n - 0.1); axT.axis("off")
    xmax = draw_tree(axT, root, branch_val, norm, lw=2.2)
    axT.set_xlim(-xmax * 0.02, xmax * 1.02)

    y = {l.name: l.y for l in leaves}
    for label, members, col in groups:
        ys = [y[m] for m in members if m in y]
        if not ys: continue
        y0, y1 = min(ys) - 0.46, max(ys) + 0.46
        axT.add_patch(plt.Rectangle((xmax * 1.006, y0), xmax * 0.026, y1 - y0,
                      color=col, lw=0, alpha=0.92, clip_on=False))
        axT.text(xmax * 1.05, (y0 + y1) / 2, label, va="center", ha="left",
                 fontsize=6.6, color="#3a3a3a")
    for l in leaves:
        axT.plot([l.x, xmax], [l.y, l.y], ls=(0, (1, 1.5)), lw=0.5, color="#cfcfcf", zorder=1)
        axT.text(xmax * 1.245, l.y, prettify(l.name), style="italic", fontsize=7.3,
                 va="center", ha="left")

    for l in leaves:
        axB.barh(l.y, gained.get(l.name, 0), height=0.6, color="#B2182B", zorder=3)
        axB.barh(l.y, -lost.get(l.name, 0), height=0.6, color="#2166AC", zorder=3)
    bmax = max(1, max(max(gained.values(), default=0), max(lost.values(), default=0)))
    axB.set_ylim(-0.9, n - 0.1); axB.set_xlim(-bmax * 1.06, bmax * 1.06)
    for s in ["top", "left", "right"]: axB.spines[s].set_visible(False)
    axB.spines["bottom"].set_position(("outward", 4)); axB.spines["bottom"].set_color("#888")
    axB.set_yticks([]); axB.set_xticks([-bmax, 0, bmax])
    axB.set_xticklabels([int(bmax), 0, int(bmax)])
    axB.tick_params(axis="x", labelsize=6, length=2, color="#888")
    axB.axvline(0, color="#aaa", lw=0.5, zorder=1)
    axB.annotate("copies lost", (-bmax, n - 0.2), fontsize=6.4, color="#2166AC",
                 ha="left", va="bottom")
    axB.annotate("copies gained", (bmax, n - 0.2), fontsize=6.4, color="#B2182B",
                 ha="right", va="bottom")

    cax = fig.add_axes([0.06, 0.05, 0.2, 0.013])
    cb = mpl.colorbar.ColorbarBase(cax, cmap=DIVER, norm=norm, orientation="horizontal",
                                   extend="both")
    cb.set_label("net change on branch (gene copies)", fontsize=6.5)
    cb.ax.tick_params(labelsize=6, length=2)
    # an empty --title suppresses panel letters and the title (web-display variant)
    if title:
        fig.text(0.055, 0.945, "a", fontsize=15, fontweight="bold")
        fig.text(0.093, 0.945, title, fontsize=9.2, va="center")
    if subtitle:
        fig.text(0.055, 0.915, subtitle, fontsize=6.8, va="center", color="#666")
    if fdr_map:
        n_sig = sum(1 for (_p, q) in fdr_map.values() if q < 0.05)
        n_tot = len(fdr_map)
        fig.text(0.055, 0.892, f"BH FDR < 0.05: {n_sig}/{n_tot} families non-neutral",
                 fontsize=6.8, va="center", color="#444")
    _save(fig, out_base, formats); plt.close(fig)

def figure_family(root, df, fam, out_base, formats, use_blen=True, fam_name=None,
                  fdr=None, root_counts=None):
    g = df[df.FamilyID == fam]
    if g.empty: return False
    gm = {str(r.TaxonID): (int(r.Count), int(r.Change), float(r.Pvalue))
          for r in g.itertuples()}
    branch_val = {node_key(n): gm[node_key(n)][1] for n in root.walk()
                  if node_key(n) in gm}
    counts = {node_key(n): gm[node_key(n)][0] for n in root.walk() if node_key(n) in gm}
    # result_summary.tsv has no root row (no incoming branch, no Change/Pvalue). The root's
    # ancestral copy number must come from that family's own ASR tree (load_root_counts),
    # never from the shared topology's root.count — that is just the first family's value.
    if root_counts is not None:
        rc = root_counts.get(fam)
        if rc is not None:
            counts[node_key(root)] = rc
    sig = {node_key(n): (gm[node_key(n)][2] < 0.05) for n in root.walk()
           if node_key(n) in gm}
    leaves = layout(root, use_blen); n = len(leaves)
    vmax = max(1, max((abs(v) for v in branch_val.values()), default=1))
    norm = TwoSlopeNorm(vmin=-vmax, vcenter=0, vmax=vmax)
    fig = plt.figure(figsize=(6.4, max(4.5, 0.27 * n + 1.2)))
    ax = fig.add_axes([0.02, 0.07, 0.66, 0.84]); ax.axis("off"); ax.set_ylim(-0.9, n - 0.1)
    xmax = draw_tree(ax, root, branch_val, norm, lw=2.4, counts=counts, sig=sig)
    ax.set_xlim(-xmax * 0.02, xmax * 1.02)
    for l in leaves:
        ax.plot([l.x, xmax], [l.y, l.y], ls=(0, (1, 1.5)), lw=0.5, color="#cfcfcf", zorder=1)
        star = " *" if sig.get(l.name) else ""
        ax.text(xmax * 1.06, l.y, prettify(l.name) + star, style="italic", fontsize=7.3,
                va="center")
    cax = fig.add_axes([0.12, 0.05, 0.32, 0.014])
    cb = mpl.colorbar.ColorbarBase(cax, cmap=DIVER, norm=norm, orientation="horizontal",
                                   extend="both")
    cb.set_label("change in copy number on branch", fontsize=6.6)
    cb.ax.tick_params(labelsize=6, length=2)
    fig.text(0.02, 0.955, "b", fontsize=15, fontweight="bold")
    ttl = f"{fam_name} (TC {fam})" if fam_name else f"TC {fam}"
    fig.text(0.06, 0.955, ttl, fontsize=10, va="center", style="italic")
    fig.text(0.06, 0.93, "* branch p < 0.05", fontsize=6.8, color="#666", va="center")
    if fdr is not None:
        # family-level p and BH-adjusted FDR annotated top-right; red if FDR<0.05, else grey.
        raw_p, q = fdr
        fig.text(0.99, 0.955, f"p={_fmt_p(raw_p)} · BH FDR={_fmt_p(q)}",
                 fontsize=7, ha="right", va="center",
                 color="#B2182B" if q < 0.05 else "#888")
    _save(fig, out_base, formats); plt.close(fig)
    return True

def _save(fig, base, formats):
    for fmt in formats:
        fig.savefig(f"{base}.{fmt}", dpi=300 if fmt in ("png", "jpg") else None,
                    bbox_inches="tight")

