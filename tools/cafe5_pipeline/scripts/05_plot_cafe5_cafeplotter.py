r"""
plot_cafe5_publication.py — render CAFE5 output as publication-ready
gene-family expansion/contraction trees.

Design
--------
cafeplotter does what it is good at — parsing the CAFE5 ASR tree and producing
result_summary.tsv; this script takes over the plotting step with a custom matplotlib renderer:

  * diverging palette (contraction = blue / neutral / expansion = red; ColorBrewer RdBu, colorblind- and print-safe)
  * clade color strips + rotated labels (algae -> bryophytes -> ferns -> ANA -> mono-/dicots)
  * italic Latin names + dashed leader lines
  * summary figure with a per-species net gain/loss diverging bar panel on the right
  * per-family figures with per-node copy-number labels + significant-branch stars
  * SVG/PDF with editable vector text (svg.fonttype=none, pdf.fonttype=42)

Outputs
----
    outdir/
    ├── summary_all_gene_family.<fmt>      global tree + net-change panel
    ├── gene_family/<FamilyID>.<fmt>       one tree per (or per selected/significant) family
    └── result_summary.tsv                 reused / generated by cafeplotter

Usage
----
    python3 plot_cafe5_publication.py \
        --cafe-dir <CAFE5 output dir> \
        --outdir   <figure output dir> \
        --format   pdf,svg,png \
        --families significant

Dependencies: matplotlib, numpy, pandas; cafeplotter only when result_summary.tsv must be generated.
"""

