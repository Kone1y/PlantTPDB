def load_family_fdr(cafe_dir):
    """Return {family_id: (raw_pvalue, bh_fdr)}.
    Prefer Base_family_results.fdr.tsv; if absent, compute BH on the fly from
    Base_family_results.txt (so the plotter also works standalone);
    if neither exists, return {} (no annotation)."""
    fdr_tsv = os.path.join(cafe_dir, "Base_family_results.fdr.tsv")
    if os.path.isfile(fdr_tsv):
        out = {}
        with open(fdr_tsv) as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                fam = (r.get("#FamilyID") or r.get("FamilyID") or "").lstrip("#")
                try:
                    out[fam] = (float(r["pvalue"]), float(r["BH_FDR"]))
                except (KeyError, ValueError, TypeError):
                    continue
        if out:
            return out
    src = os.path.join(cafe_dir, "Base_family_results.txt")
    if not os.path.isfile(src):
        return {}
    fams, ps = [], []
    with open(src) as fh:
        fh.readline()  # header
        for line in fh:
            line = line.rstrip("\n")
            if not line.strip():
                continue
            parts = line.split("\t")
            if len(parts) < 2:
                continue
            try:
                ps.append(float(parts[1]))
            except ValueError:
                continue
            fams.append(parts[0])
    if not fams:
        return {}
    q = false_discovery_control(ps, method="bh")
    return {fams[i]: (float(ps[i]), min(1.0, float(q[i]))) for i in range(len(fams))}

def sanitize_asr_trees(cafe_dir):
    tmp = tempfile.mkdtemp(prefix="cafeplotter_in_")
    for f in os.listdir(cafe_dir):
        src = os.path.join(cafe_dir, f); dst = os.path.join(tmp, f)
        if not os.path.isfile(src): continue
        if f.endswith(".tre"):
            c = open(src, encoding="utf-8").read()
            c2 = re.sub(r"(TREE\s+)(\S+)(\s*=)",
                        lambda m: (m.group(1) + "'" + m.group(2) + "'" + m.group(3))
                        if "-" in m.group(2) else m.group(0), c)
            open(dst, "w", encoding="utf-8").write(c2)
        else:
            os.symlink(os.path.abspath(src), dst)
    return tmp

def ensure_summary(cafe_dir, outdir, fmt, binpath):
    tsv = os.path.join(outdir, "result_summary.tsv")
    if os.path.isfile(tsv): return tsv
    src_tsv = os.path.join(cafe_dir, "result_summary.tsv")
    if os.path.isfile(src_tsv):
        shutil.copy2(src_tsv, tsv); return tsv
    binpath = binpath or (DEFAULT_CAFEPLOTTER if os.access(DEFAULT_CAFEPLOTTER, os.X_OK)
                          else shutil.which("cafeplotter"))
    if not binpath: sys.exit("[ERROR] result_summary.tsv is required but cafeplotter was not found to generate it")
    tmp = sanitize_asr_trees(cafe_dir)
    try:
        subprocess.run([binpath, "-i", tmp, "-o", outdir, "--format", fmt], check=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if not os.path.isfile(tsv):
        alt = os.path.join(outdir, "result_summary.tsv")
        if os.path.isfile(alt): return alt
        sys.exit("[ERROR] cafeplotter did not produce result_summary.tsv")
    return tsv

# ===================================================================
# 6. CLI
# ===================================================================
def main():
    ap = argparse.ArgumentParser(description="CAFE5 -> publication-grade expansion/contraction trees")
    ap.add_argument("--cafe-dir", required=True)
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--tree", default=None, help="explicit topology (newick/nexus); default: *.tre inside cafe-dir")
    ap.add_argument("--format", default="pdf,svg,png", help="comma-separated: pdf,svg,png")
    ap.add_argument("--families", default="significant",
                    help="'all' / 'significant' / comma-separated FamilyID list / 'none'")
    ap.add_argument("--vmax", type=float, default=None, help="branch-color saturation threshold for the summary figure (default: adaptive 80th percentile)")
    ap.add_argument("--cladogram", action="store_true", help="ignore branch lengths; draw with equal spacing")
    ap.add_argument("--font", default=None)
    ap.add_argument("--group-json", default=None, help="clade-group JSON: [[label,[tips],color],...]")
    ap.add_argument("--title", default="", help="figure title; default empty (no title or panel letters)")
    ap.add_argument("--subtitle", default="CAFE5 birth–death model · red = expansion, blue = contraction")
    ap.add_argument("--cafeplotter", default=None)
    ap.add_argument("--fam-names-json", default=None, help="{FamilyID: display name} mapping")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    if os.path.exists(args.outdir) and args.force:
        shutil.rmtree(args.outdir)
    os.makedirs(args.outdir, exist_ok=True)
    os.makedirs(os.path.join(args.outdir, "gene_family"), exist_ok=True)
    formats = [f.strip() for f in args.format.split(",") if f.strip()]
    set_style(args.font)

    tsv = ensure_summary(args.cafe_dir, args.outdir, formats[0], args.cafeplotter)
    df = pd.read_csv(tsv, sep="\t")
    root = read_tree(args.cafe_dir, args.tree)
    root_counts = load_root_counts(args.cafe_dir, args.tree)
    use_blen = not args.cladogram

    groups = DEFAULT_GROUPS
    if args.group_json:
        groups = [tuple(x) for x in json.load(open(args.group_json))]
    fam_names = json.load(open(args.fam_names_json)) if args.fam_names_json else {}

    fdr_map = load_family_fdr(args.cafe_dir)
    if fdr_map:
        n_sig = sum(1 for (_p, q) in fdr_map.values() if q < 0.05)
        print(f"[INFO] family-level BH FDR: {len(fdr_map)} families, FDR<0.05: {n_sig}")

    print("[INFO] drawing summary_all_gene_family ...")
    figure_summary(root, df, os.path.join(args.outdir, "summary_all_gene_family"),
                   formats, groups, vmax=args.vmax, use_blen=use_blen,
                   title=args.title, subtitle=args.subtitle, fdr_map=fdr_map)

    if args.families.lower() == "none":
        fams = []
    elif args.families.lower() == "all":
        fams = sorted(df.FamilyID.unique())
    elif args.families.lower() == "significant":
        sigf = df[df.Pvalue < 0.05].FamilyID.unique()
        fams = sorted(sigf)
    else:
        fams = [f.strip() for f in args.families.split(",") if f.strip()]

    print(f"[INFO] drawing {len(fams)} families ...")
    for fam in fams:
        base = os.path.join(args.outdir, "gene_family", fam.replace("/", "_"))
        figure_family(root, df, fam, base, formats, use_blen=use_blen,
                      fam_name=fam_names.get(fam), fdr=fdr_map.get(fam),
                      root_counts=root_counts)

    print(f"[DONE] output directory: {os.path.abspath(args.outdir)}")

if __name__ == "__main__":
    main()
