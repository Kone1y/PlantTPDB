# 2. lightweight Newick / Nexus parsing (no external phylogenetics libraries)
# ===================================================================
class Node:
    __slots__ = ("name", "cid", "blen", "children", "x", "y", "parent", "count")
    def __init__(self):
        self.name = None; self.cid = None; self.blen = 0.0
        self.children = []; self.x = 0.0; self.y = 0.0; self.parent = None
        self.count = None  # ASR ancestral copy number (the trailing _count in newick labels)
    def is_leaf(self): return not self.children
    def leaves(self):
        if self.is_leaf(): return [self]
        out = []
        for c in self.children: out += c.leaves()
        return out
    def walk(self):
        yield self
        for c in self.children:
            yield from c.walk()

def parse_newick(s):
    s = s.strip().rstrip(";"); pos = 0
    def read_label():
        nonlocal pos
        m = re.match(r"[^,\(\):;]*", s[pos:]); pos += len(m.group(0)); return m.group(0)
    def read_blen():
        nonlocal pos
        if pos < len(s) and s[pos] == ":":
            pos += 1; m = re.match(r"[0-9eE\.\+\-]+", s[pos:]); pos += len(m.group(0))
            return float(m.group(0))
        return 0.0
    def parse():
        nonlocal pos
        node = Node()
        if s[pos] == "(":
            pos += 1
            while True:
                node.children.append(parse())
                if s[pos] == ",": pos += 1; continue
                if s[pos] == ")": pos += 1; break
        lbl = read_label(); node.blen = read_blen()
        m = re.search(r"<(\d+)>", lbl)                    # CAFE node id <32>
        if m: node.cid = m.group(1)
        # ASR ancestral copy number: the trailing _count, e.g. <27>_15, Acorus<1>_36, <47>*_58.
        # read_label truncates at ':', so lbl has no branch length; _(\d+)$ always hits the trailing count.
        mc = re.search(r"_(\d+)\s*$", lbl)
        if mc: node.count = int(mc.group(1))
        # CAFE ASR labels look like name<id>[*]_count (e.g. Acorus_calamus<1>_36,
        # significant leaf Ananas<2>*_27, internal node <45>_35). Keep only the species name
        # before '<' and strip <id>, the significance '*' and the _count suffix — otherwise
        # node.name would carry "_36"/"*_27" and fail to match TaxonID in result_summary.tsv.
        # without '<' (plain newick), split("<")[0] returns the whole string (backward compatible).
        nm = lbl.split("<")[0].strip("'\" ")
        node.name = nm or None
        for c in node.children: c.parent = node
        return node
    return parse()

def _resolve_tree_path(cafe_dir, explicit=None):
    """Locate the .tre file: --tree first, else *_asr.tre inside cafe-dir."""
    path = explicit
    if not path:
        cand = [os.path.join(cafe_dir, f) for f in os.listdir(cafe_dir)
                if f.endswith(".tre")]
        # prefer Base_asr.tre / *_asr.tre
        cand.sort(key=lambda p: (0 if "asr" in os.path.basename(p).lower() else 1, p))
        if not cand:
            sys.exit(f"[ERROR] no *.tre found in {cafe_dir} and no --tree given")
        path = cand[0]
    return path

def read_tree(cafe_dir, explicit=None):
    """Take the topology of the first tree from --tree or a CAFE5 *.tre (Nexus)."""
    path = _resolve_tree_path(cafe_dir, explicit)
    txt = open(path, encoding="utf-8", errors="ignore").read()
    m = re.search(r"TREE[^=]*=\s*(\[[^\]]*\])?\s*(\([^\n;]+;)", txt, re.I)
    nwk = m.group(2) if m else txt  # falls back to a plain newick file
    print(f"[INFO] topology taken from: {path}")
    return parse_newick(nwk)

def load_root_counts(cafe_dir, explicit=None):
    """{FamilyID: ancestral copy number at the root of that family}.

    result_summary.tsv has no root row (the root has no incoming branch, hence no Change/Pvalue),
    so root counts must be parsed per family from its own ASR tree label <id>_count.
    Note: read_tree parses only the first tree as the shared topology, so root.count is
    always the root count of the first family (e.g. 1.A.1=15) — hence this per-family map.
    """
    path = _resolve_tree_path(cafe_dir, explicit)
    txt = open(path, encoding="utf-8", errors="ignore").read()
    out = {}
    for name, nwk in re.findall(r"TREE\s+(\S+)\s*=\s*(\([^\n;]+;)", txt):
        r = parse_newick(nwk)
        if r.count is not None:
            out[name] = r.count
    return out


